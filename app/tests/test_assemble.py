import os
from pathlib import Path

import rtoml

from mocapapp.cli.main import main
from mocapapp.core.config_gen import build_config, gui_flags_set, overrides
from mocapapp.core.session import Layout, Session, Trial, load_session


def test_config_has_no_gui_flags_and_trial_height():
    s = Session(n_trials=1, trials=[Trial(label="3", code="PA26-ABCDEFG", height_m=1.78)], cameras=[])
    text = build_config(s, s.trials[0], scene_points=[[0, 0, 0], [1, 0, 0]])
    assert gui_flags_set(text) == []
    cfg = rtoml.loads(text)
    assert cfg["project"]["participant_height"] == 1.78
    assert cfg["pose"]["pose_model"] == "Body_with_feet" and cfg["pose"]["blur_faces"] is True
    assert cfg["filtering"]["butterworth"]["cut_off_frequency"] == 6
    assert cfg["calibration"]["calculate"]["extrinsics"]["scene"]["object_coords_3d"][1] == [1.0, 0.0, 0.0]
    assert cfg["kinematics"]["make_bvh"] is True
    assert "# Generated by mocapapp" in text and "PA26-ABCDEFG" in text


def test_auto_height_when_missing():
    s = Session(n_trials=1, trials=[Trial(label="1", code="X")], cameras=[])
    assert overrides(s, s.trials[0])["project.participant_height"] == "auto"


def test_cli_new_validate_assemble(camera_dirs, tmp_path, capsys, monkeypatch):
    dirs = camera_dirs(n_cams=2, trial_names=("run1", "run2"))
    out = tmp_path / "sessions"
    args = ["session", "new", "--study", "T1", "--trials", "2", "--heights", "178,1.65", "--out", str(out)]
    for i, d in enumerate(dirs, 1):
        args += ["--cam", f"cam{i:02d}={d}"]
    assert main(args) == 0
    root = next(out.iterdir())
    assert main(["validate", "--session", str(root)]) == 0
    assert "Trial mapping (digit)" in capsys.readouterr().out

    # a computed calibration is copied into every trial
    layout = Layout(root)
    layout.calibration_work.mkdir()
    layout.calib_file.write_text("[cam01]\nname = 'cam01'\n")
    assert main(["assemble", "--session", str(root)]) == 0

    s = load_session(root)
    assert [t.height_m for t in s.trials] == [1.78, 1.65]
    assert all(t.code.startswith("T1-") for t in s.trials)
    for t in s.trials:
        tdir = layout.trial(t.label)
        assert sorted(p.name for p in (tdir / "videos").iterdir()) == ["cam01.mp4", "cam02.mp4"]
        assert [p.name for p in (tdir / "calibration").iterdir()] == ["Calib_scene.toml"]
        assert not (layout.trials / "Config.toml").exists()
        # upstream accepts it as a self-contained trial project (upstream-notes §1)
        from Pose2Sim.Pose2Sim import read_config_files

        monkeypatch.chdir(tdir)
        level, configs = read_config_files(None)
        assert level == 1 and configs[0]["project"]["participant_height"] == t.height_m
        session_dir = Path("..").resolve()
        assert "Config.toml" not in os.listdir(session_dir)  # so stages fall back to the trial folder

    # resume: running again reuses the converted inputs
    assert main(["assemble", "--session", str(root)]) == 0


def test_cli_rejects_non_ascii_output(camera_dirs, tmp_path):
    dirs = camera_dirs(n_cams=2)
    code = main(["session", "new", "--trials", "2", "--out", str(tmp_path / "sessiøn"),
                 "--cam", f"cam01={dirs[0]}", "--cam", f"cam02={dirs[1]}"])
    assert code == 1


def test_assemble_dry_run_writes_nothing(camera_dirs, tmp_path):
    dirs = camera_dirs(n_cams=2)
    out = tmp_path / "s"
    main(["session", "new", "--trials", "2", "--out", str(out),
          "--cam", f"cam01={dirs[0]}", "--cam", f"cam02={dirs[1]}"])
    root = next(out.iterdir())
    assert main(["assemble", "--session", str(root), "--dry-run"]) == 0
    assert not (root / "inputs").exists() and not (root / "trials").exists()
