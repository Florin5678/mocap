"""Per-trial Config.toml: upstream's demo config (comments kept) plus enforced, non-interactive overrides."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import Pose2Sim
import tomlkit

from mocapapp.core.session import Session, Trial

TEMPLATE = Path(Pose2Sim.__file__).parent / "Demo_SinglePerson" / "Config.toml"

# Every upstream switch that opens a window or waits for a click. All must be false (PROJECT.md §3).
GUI_FLAGS = ("display_detection", "synchronization_gui", "display_sync_plots", "display_figures",
             "show_detection_intrinsics", "show_reprojection_error")


class ConfigDriftError(KeyError):
    """Upstream renamed or removed a key the app sets; update config_gen.py."""


def _set(doc, dotted: str, value: Any) -> None:
    *parents, key = dotted.split(".")
    table = doc
    for p in parents:
        if p not in table:
            raise ConfigDriftError(f"Upstream Config.toml has no [{'.'.join(parents)}] (needed for {dotted}).")
        table = table[p]
    if key not in table:
        raise ConfigDriftError(f"Upstream Config.toml has no key {dotted}.")
    table[key] = value


def overrides(session: Session, trial: Trial, scene_points: list[list[float]] | None = None) -> dict[str, Any]:
    s = session.settings
    values: dict[str, Any] = {
        "project.participant_height": trial.height_m if trial.height_m is not None else "auto",
        "project.multi_person": False,
        "project.frame_rate": "auto",
        "pose.pose_model": "Body_with_feet",
        "pose.mode": s.pose_mode,
        "pose.device": s.device,
        "pose.display_detection": False,
        "pose.save_video": "to_video",
        "pose.blur_faces": True,
        "synchronization.synchronization_gui": False,
        "synchronization.display_sync_plots": False,
        "synchronization.save_sync_plots": True,
        "calibration.calibration_type": "calculate",
        "calibration.calculate.intrinsics.board_type": s.board_type,
        "calibration.calculate.intrinsics.corners_nb": list(s.corners_nb),
        "calibration.calculate.intrinsics.square_size": s.square_size_mm,
        "calibration.calculate.intrinsics.marker_resolution": s.marker_resolution,
        "calibration.calculate.intrinsics.show_detection_intrinsics": False,
        "calibration.calculate.intrinsics.overwrite_intrinsics": False,
        "calibration.calculate.extrinsics.extrinsics_method": "scene",
        "calibration.calculate.extrinsics.show_reprojection_error": False,
        "triangulation.make_c3d": True,
        "filtering.reject_outliers": True,
        "filtering.type": s.filter.type,
        "filtering.display_figures": False,
        "filtering.make_c3d": True,
        f"filtering.{s.filter.type}.cut_off_frequency": s.filter.cutoff_hz,
        "markerAugmentation.make_c3d": True,
        "kinematics.use_augmentation": s.use_augmentation,
        "kinematics.make_bvh": s.make_bvh,
    }
    if s.filter.type == "butterworth":
        values["filtering.butterworth.order"] = s.filter.order
    if scene_points:
        # Provenance only: the app computes extrinsics itself, upstream calibration is never run.
        values["calibration.calculate.extrinsics.scene.object_coords_3d"] = [list(map(float, p)) for p in scene_points]
    return values


def build_config(session: Session, trial: Trial, scene_points: list[list[float]] | None = None) -> str:
    doc = tomlkit.parse(TEMPLATE.read_text(encoding="utf-8"))
    for dotted, value in overrides(session, trial, scene_points).items():
        _set(doc, dotted, value)
    header = (f"# Generated by mocapapp {session.app_version} for trial {trial.label} ({trial.code}).\n"
              "# Edits here are overwritten when the trial is re-assembled; change settings in the app instead.\n\n")
    return header + tomlkit.dumps(doc)


def gui_flags_set(config_text: str) -> list[str]:
    """Dotted names of any interactive flag that is not false (for tests and pre-run checks)."""
    found: list[str] = []

    def walk(table, prefix=""):
        for key, value in table.items():
            name = f"{prefix}{key}"
            if isinstance(value, dict):
                walk(value, name + ".")
            elif key in GUI_FLAGS and value is not False:
                found.append(name)

    walk(tomlkit.parse(config_text).unwrap())
    return found
